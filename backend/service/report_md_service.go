package service

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"FusionWeb/backend/utils"
)

func (s *ReportService) GenerateMDReport(outputPath string) error {
	data, err := s.CollectReportData()
	if err != nil {
		return err
	}

	md := s.buildMarkdownContent(data)
	if err := os.WriteFile(outputPath, []byte(md), 0644); err != nil {
		return fmt.Errorf("写入 Markdown 文件失败: %w", err)
	}
	if err := s.saveReportMetadata("md", outputPath); err != nil {
		return err
	}
	return nil
}

// buildMarkdownContent 构建 dddd 风格的 Markdown 报告。
func (s *ReportService) buildMarkdownContent(data *ReportData) string {
	var md strings.Builder

	md.WriteString("# FusionWeb 扫描报告\n\n")
	md.WriteString(fmt.Sprintf("**生成时间**: %s\n\n", utils.GetCurrentTimeString()))
	md.WriteString("---\n\n")

	writeMDStatsSection(&md, data)
	writeMDTargetsSection(&md, reportTargetList(data))
	writeMDWebServiceSection(&md, data.ReconResults)
	writeMDFingerprintSection(&md, data.Fingerprints)
	writeMDVulnSection(&md, data.Vulnerabilities)
	writeMDPortServiceSection(&md, data.ReconResults)

	md.WriteString("---\n\n")
	md.WriteString("*Generated by FusionWeb*\n")
	return md.String()
}

func writeMDStatsSection(md *strings.Builder, data *ReportData) {
	md.WriteString("## 📊 统计概览\n\n")
	md.WriteString("| 类型 | 数量 |\n")
	md.WriteString("|------|------|\n")
	md.WriteString(fmt.Sprintf("| 端口 | %d |\n", data.Statistics.PortCount))
	md.WriteString(fmt.Sprintf("| URL | %d |\n", data.Statistics.URLCount))
	md.WriteString(fmt.Sprintf("| 指纹 | %d |\n", data.Statistics.FingerprintCount))
	md.WriteString(fmt.Sprintf("| 漏洞总数 | %d |\n", data.Statistics.VulnCount))
	md.WriteString("\n")

	if data.Statistics.VulnCount > 0 {
		md.WriteString("### 漏洞等级分布\n\n")
		md.WriteString("| 等级 | 数量 |\n")
		md.WriteString("|------|------|\n")
		md.WriteString(fmt.Sprintf("| 🔴 严重 | %d |\n", data.Statistics.CriticalCount))
		md.WriteString(fmt.Sprintf("| 🟠 高危 | %d |\n", data.Statistics.HighCount))
		md.WriteString(fmt.Sprintf("| 🟡 中危 | %d |\n", data.Statistics.MediumCount))
		md.WriteString(fmt.Sprintf("| 🟢 低危 | %d |\n", data.Statistics.LowCount))
		md.WriteString(fmt.Sprintf("| 🔵 信息 | %d |\n", data.Statistics.InfoCount))
		md.WriteString("\n")
	}
	md.WriteString("---\n\n")
}

func writeMDTargetsSection(md *strings.Builder, targets []string) {
	if len(targets) == 0 {
		return
	}
	md.WriteString("## 🎯 目标\n\n")
	for i, target := range targets {
		md.WriteString(fmt.Sprintf("%d. `%s`\n", i+1, escapeMarkdownInline(target)))
	}
	md.WriteString("\n---\n\n")
}

func writeMDWebServiceSection(md *strings.Builder, results []ReconSummary) {
	_, webResults := splitReportReconResults(results)
	if len(webResults) == 0 {
		return
	}

	md.WriteString("## 🌐 Web服务\n\n")
	md.WriteString("| 目标 | 状态码 | 标题 |\n")
	md.WriteString("|------|--------|------|\n")
	for _, r := range webResults {
		md.WriteString(fmt.Sprintf("| `%s` | %s | %s |\n",
			escapeMarkdownTableCell(r.Target),
			escapeMarkdownTableCell(defaultText(r.StatusCode, "-")),
			escapeMarkdownTableCell(defaultText(r.Title, "-"))))
	}
	md.WriteString("\n---\n\n")
}

func writeMDFingerprintSection(md *strings.Builder, fingerprints []FingerprintSummary) {
	if len(fingerprints) == 0 {
		return
	}

	fingerprintMap := make(map[string][]string)
	for _, fp := range fingerprints {
		target := strings.TrimSpace(fp.Target)
		if target == "" {
			target = "-"
		}
		fingerprint := strings.TrimSpace(fp.Fingerprint)
		if fingerprint == "" {
			continue
		}
		fingerprintMap[target] = append(fingerprintMap[target], fingerprint)
	}
	if len(fingerprintMap) == 0 {
		return
	}

	targets := make([]string, 0, len(fingerprintMap))
	for target := range fingerprintMap {
		targets = append(targets, target)
	}
	sort.Strings(targets)

	md.WriteString("## 🔎 指纹识别结果\n\n")
	md.WriteString("| 目标 | 指纹 |\n")
	md.WriteString("|------|------|\n")
	for _, target := range targets {
		md.WriteString(fmt.Sprintf("| `%s` | %s |\n",
			escapeMarkdownTableCell(target),
			escapeMarkdownTableCell(strings.Join(fingerprintMap[target], ", "))))
	}
	md.WriteString("\n---\n\n")
}

func writeMDVulnSection(md *strings.Builder, vulnerabilities []VulnSummary) {
	if len(vulnerabilities) == 0 {
		return
	}

	md.WriteString("## 🐛 漏洞详情\n\n")
	for i, vuln := range vulnerabilities {
		displayName := strings.TrimSpace(vuln.Name)
		if displayName == "" {
			displayName = vuln.TemplateID
		}
		if displayName == "" {
			displayName = "未命名漏洞"
		}

		md.WriteString(fmt.Sprintf("### %d. %s (%s)\n\n", i+1, displayName, defaultText(vuln.TemplateID, "-")))
		if vuln.MatcherName != "" {
			md.WriteString(fmt.Sprintf("**威胁类型**: %s\n\n", vuln.MatcherName))
		}
		if vuln.Author != "" {
			md.WriteString(fmt.Sprintf("**作者信息**: %s\n\n", vuln.Author))
		}
		md.WriteString(fmt.Sprintf("**目标信息**: `%s`\n\n", escapeMarkdownInline(vuln.Target)))
		md.WriteString(fmt.Sprintf("**等级**: **%s**\n\n", strings.ToUpper(vuln.Severity)))
		if vuln.Description != "" {
			md.WriteString(fmt.Sprintf("**描述内容**: %s\n\n", vuln.Description))
		}
		md.WriteString(fmt.Sprintf("**发现时间**: %s\n\n", formatTimeString(vuln.Time)))

		if strings.TrimSpace(vuln.Request) != "" {
			md.WriteString("**请求**:\n\n```http\n")
			md.WriteString(formatPacket(vuln.Request))
			md.WriteString("\n```\n\n")
		}
		if strings.TrimSpace(vuln.Response) != "" {
			md.WriteString("**响应**:\n\n```http\n")
			md.WriteString(formatPacket(vuln.Response))
			md.WriteString("\n```\n\n")
		}
		md.WriteString("---\n\n")
	}
}

func writeMDPortServiceSection(md *strings.Builder, results []ReconSummary) {
	portResults, _ := splitReportReconResults(results)
	if len(portResults) == 0 {
		return
	}

	md.WriteString("## 🔌 端口/服务\n\n")
	md.WriteString("| IP | 端口 | 协议 |\n")
	md.WriteString("|------|------|------|\n")
	for _, r := range portResults {
		host := r.Host
		port := r.Port
		if host == "" || port == "" {
			host, port = splitReportHostPort(r.Target)
		}
		protocol := defaultText(r.Protocol, "TCP")
		md.WriteString(fmt.Sprintf("| %s | %s | %s |\n",
			escapeMarkdownTableCell(host),
			escapeMarkdownTableCell(port),
			escapeMarkdownTableCell(strings.ToUpper(protocol))))
	}
	md.WriteString("\n---\n\n")
}

func escapeMarkdownTableCell(s string) string {
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.ReplaceAll(s, "|", "\\|")
}

func escapeMarkdownInline(s string) string {
	return strings.ReplaceAll(strings.TrimSpace(s), "`", "\\`")
}
