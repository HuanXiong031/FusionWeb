// ========================================
// 内存回收模块（Memory Garbage Collection）
//
// 功能概述：
//
//	提供自动内存回收功能，定期触发 Go 运行时 GC 并释放操作系统层面的内存。
//	通过后台协程每 10 秒执行一次内存回收，降低长时间运行时的内存占用。
//
// 核心特性：
//  1. 自动启动：包被导入时自动启动后台 GC 协程
//  2. 定期回收：每 10 秒执行一次内存回收
//  3. 双重回收：同时触发 Go 运行时 GC 和操作系统内存释放
//
// 使用说明：
//   - 无需手动调用，导入 common 包后自动生效
//   - GC() 函数可手动调用进行即时内存回收
//
// 注意事项：
//   - GC 操作会暂停程序执行，频率不宜过高
//   - 10 秒间隔是平衡性能和内存占用的折中方案
//
// ========================================
package common

import (
	"runtime"
	"runtime/debug"
	"time"
)

// init 启动后台内存回收协程，周期调用 GC 降低内存占用
//
// 功能说明：
//
//	在包被导入时自动启动一个后台协程，每 10 秒执行一次内存回收。
//	这有助于在长时间运行的桌面应用中控制内存占用。
//
// 执行频率：
//   - 每 10 秒执行一次 GC
//   - 间隔时间可根据实际需求调整
func init() {
	go func() {
		for {
			GC()
			time.Sleep(10 * time.Second)
		}
	}()
}

// GC 触发 Go 运行时 GC，并尝试释放操作系统层面的内存
//
// 功能说明：
//
//	执行双重内存回收：
//	1. runtime.GC()：触发 Go 运行时的垃圾回收
//	2. debug.FreeOSMemory()：尝试将内存返还给操作系统
//
// 使用场景：
//   - 自动调用：由 init() 启动的后台协程定期调用
//   - 手动调用：在内存占用较高时手动调用进行即时回收
//
// 注意事项：
//   - GC 操作会暂停程序执行（Stop The World）
//   - 频繁调用可能影响性能，建议间隔至少 10 秒
func GC() {
	runtime.GC()
	debug.FreeOSMemory()
}
