export function TasksView({ demoMode, onOpenTask }: { demoMode: boolean; onOpenTask: (taskId: string) => void }) {
  const queryClient = useQueryClient()
  const query = useQuery({
    queryKey: ['tasks'],
    queryFn: getTasks,
    enabled: !demoMode,
    refetchInterval: 3000,
  })
  const tasks = demoMode ? demoTasks : asList<TaskRow>(query.data)
  const actionMutation = useMutation({
    mutationFn: async ({ action, taskId }: { action: string; taskId: string }) => {
      if (demoMode) return null
      if (action === 'pause') return pauseTask(taskId)
      if (action === 'resume') return resumeTask(taskId)
      if (action === 'stop') return stopTask(taskId)
      if (action === 'delete') return deleteTask(taskId)
      return null
    },
    onSuccess: () => {
      toast.success('操作成功')
      queryClient.invalidateQueries({ queryKey: ['tasks'] })
    },
    onError: (error: any) => toast.error(error.message || '操作失败'),
  })
  const columns = getTaskColumns(onOpenTask, (action, taskId) => actionMutation.mutate({ action, taskId }))

  return (
    <div>
      <PageTitle title="任务列表" description="支持搜索、查看、暂停、恢复、停止和删除。" />
      <DataTable
        columns={columns}
        data={tasks}
        searchPlaceholder="搜索任务名称或目标"
        emptyTitle="暂无任务"
        paginationStorageKey="tasks"
        toolbar={
          <Button variant="outline" onClick={() => queryClient.invalidateQueries({ queryKey: ['tasks'] })}>
            <RefreshCw className="size-4" />
            刷新
          </Button>
        }
      />
    </div>
  )
}
